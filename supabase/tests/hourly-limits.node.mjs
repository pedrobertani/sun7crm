import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
test('limites horários: criação 6; reset 5 por destino e 30 por solicitante',async t=>{
 const db=new PGlite(); t.after(()=>db.close());
 await db.exec(`create schema crm_private;
 create table crm_private.user_provisioning(request_id uuid primary key,actor_user_id uuid,company_id uuid,role text,fingerprint text,state text default 'pending',user_id uuid,membership_id uuid,created_at timestamptz default statement_timestamp());
 create table crm_private.password_reset_requests(request_id uuid primary key,actor_user_id uuid,company_id uuid,target_user_id uuid,created_at timestamptz default statement_timestamp());
 create table crm_private.platform_admins(user_id uuid);
 create table crm_private.permission_catalog(key text);
 create function crm_private.company_role(uuid) returns text language sql as $$select 'manager'::text$$;
 create function crm_private.member_permission(uuid,text) returns boolean language sql as $$select true$$;
 create function crm_private.has_permission(uuid,text) returns boolean language sql as $$select true$$;
 create function crm_private.member_company_scope(uuid) returns boolean language sql as $$select true$$;
 create function crm_private.has_company_scope(uuid) returns boolean language sql as $$select true$$;
 create table public.crm_memberships(id uuid,company_id uuid,user_id uuid,role text,active boolean);
 create table public.crm_profiles(id uuid,password_change_required boolean,password_change_nonce uuid,password_changed_at timestamptz);
 create table public.crm_audit_events(company_id uuid,actor_user_id uuid,entity text,record_id uuid,action text);
 create function crm_private.edge_authorize_user_creation(uuid,uuid,text) returns void language sql as $$select$$;
 create function crm_private.edge_require_actor(uuid) returns void language sql as $$select$$;
 create function crm_private.is_platform_admin() returns boolean language sql as $$select true$$;
 `);
 await db.exec(await readFile(new URL('../migrations/20261030122802_crm_hourly_account_limits.sql',import.meta.url),'utf8'));
 const create=n=>db.query('select public.crm_edge_prepare_user($1,$2,$3,$4,$5)',[id(1),id(n),id(2),'seller','a'.repeat(64)]);
 for(let i=10;i<16;i++)await create(i);
 await assert.rejects(create(16),e=>e.code==='P0003');
 await db.exec("update crm_private.user_provisioning set created_at=now()-interval '61 minutes'");await create(17);
 await db.query("insert into public.crm_memberships values($1,$2,$3,'seller',true)",[id(40),id(2),id(3)]);
 const reset=(n,target=3)=>db.query('select public.crm_edge_begin_password_reset($1,$2,$3,$4)',[id(1),id(n),id(2),id(target)]);
 for(let i=20;i<25;i++)await reset(i);
 await assert.rejects(reset(25),e=>e.code==='P0003');
 await db.exec("update crm_private.password_reset_requests set created_at=now()-interval '16 minutes'");
 await assert.rejects(reset(26),e=>e.code==='P0003');
 await db.exec("update crm_private.password_reset_requests set created_at=now()-interval '61 minutes'");await reset(27);
 for(let i=4;i<10;i++)await db.query("insert into public.crm_memberships values($1,$2,$3,'seller',true)",[id(40+i),id(2),id(i)]);
 for(let i=0;i<29;i++)await reset(100+i,4+Math.floor(i/5));
 await assert.rejects(reset(200,9),e=>e.code==='P0003');
 assert.equal((await db.query("select count(*)::int n from crm_private.password_reset_requests where created_at>now()-interval '1 hour'")).rows[0].n,30);
});
